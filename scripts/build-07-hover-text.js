// The CSV is the only editable wording source. Generated JS works on HTTP and file://.
const fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.resolve(__dirname,'..'),csvFile=path.join(root,'07_skill/data/hover-descriptions.csv'),output=path.join(root,'07_skill/js/hover-text.js');
const context=vm.createContext({});
const utils=fs.readFileSync(path.join(root,'07_skill/js/map-utils.js'),'utf8');
vm.runInContext(utils.slice(utils.indexOf('function parseMapCSV('),utils.indexOf('function eventImageFiles(')),context);
context.csv=fs.readFileSync(csvFile,'utf8');
const rows=vm.runInContext('parseMapCSV(csv)',context),texts={};
for(const row of rows){
 if(!row.key||Object.hasOwn(texts,row.key))throw Error('Missing or duplicate text key: '+row.key);
 const allowed=new Set(row['変数'].trim().split(/\s+/).filter(Boolean));
 const used=new Set([...row['説明文'].matchAll(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g)].map(m=>m[1]));
 if([...used].some(key=>!allowed.has(key)))throw Error('Unknown placeholder in '+row.key);
 texts[row.key]=row['説明文'];
}
const source='// GENERATED from 07_skill/data/hover-descriptions.csv. Do not edit this file.\n'+
 'const SKILL_HOVER_TEXT=Object.freeze('+JSON.stringify(texts,null,2)+');\n'+
 `function getSkillHoverText(key,values={}){
 if(!Object.hasOwn(SKILL_HOVER_TEXT,key))throw Error('Unknown hover text: '+key);
 return SKILL_HOVER_TEXT[key].replace(/\\{([a-zA-Z][a-zA-Z0-9_]*)\\}/g,(_,name)=>{
  if(!Object.hasOwn(values,name))throw Error('Missing hover value: '+key+':'+name);
  return String(values[name]);
 });
}
// HTML-only parameter controls also use this source, before the app initialises.
if(typeof document!=='undefined')for(const element of document.querySelectorAll?.('[data-hover-key]')||[]){
 element.title=getSkillHoverText(element.dataset.hoverKey,element.dataset.hoverName?{name:element.dataset.hoverName}:{});
}
`;
new vm.Script(source,{filename:'hover-text.js'});
if(process.argv.includes('--check')){if(fs.readFileSync(output,'utf8')!==source)throw Error('Hover bundle is stale; run node scripts/build-07-hover-text.js');}
else fs.writeFileSync(output,source);
console.log('ok '+rows.length+' canonical hover texts');
