"""Generate bounded icon and white-count references from retained real crops."""
import json,argparse,base64
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'08_screen_reader/js/screen-reader-status-icons-references.js'
def build():
 refs=[]
 for name,scope,corner in [('fate','monster','top'),('energy','monster','bottom'),('mark','monster','bottom'),('heal','self','bottom'),('charge','self','bottom'),('firewall','self','top'),('attention','self','top')]:
  im=Image.open(ROOT/'tests/fixtures/screen-reader/status-icons'/f'{name}.png').convert('RGB').resize((34,34),Image.Resampling.BILINEAR);n=im.width
  points=[(x,y) for y in range(8) for x in range(8) if not (x<2 and y>5 or x>5 and y<2)]
  rgb=[v for x,y in points for v in im.getpixel((int((x+.5)*n/8),int((y+.5)*n/8)))]
  refs.append(dict(key=name,scope=scope,corner=corner,points=points,rgb=rgb))
 im=Image.open(ROOT/'tests/fixtures/screen-reader/status-icons/digit-6.png').convert('L');im=im.crop(im.getbbox())
 digit={'digit':'6','ratio':im.width/im.height,'data':base64.b64encode(bytes(int(v>110) for v in im.resize((18,28),Image.Resampling.BILINEAR).tobytes())).decode()}
 return '// Generated by scripts/build-screen-reader-status-icons.py\nwindow.ScreenReaderStatusIconReferences='+json.dumps(refs,separators=(',',':'))+';\nwindow.ScreenReaderStatusIconDigits='+json.dumps([digit],separators=(',',':'))+';\n'
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();s=build()
 if args.check:
  if OUT.read_text()!=s:raise SystemExit('Status icon references differ')
 else:OUT.write_text(s)
