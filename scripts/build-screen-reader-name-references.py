"""Build a bounded character-name dictionary; fonts are not loaded by the app."""
import argparse,base64,csv,json
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]
def template(name,font,shear):
 im=Image.new('L',(1200,150));ImageDraw.Draw(im).text((60,0),name,font=font,fill=255)
 im=im.transform(im.size,Image.Transform.AFFINE,(1,shear,0,0,1,0));im=im.crop(im.getbbox())
 data=[int(v>110) for v in im.resize((128,32),Image.Resampling.BILINEAR).tobytes()]
 packed=bytes(sum(data[i+j]<<j for j in range(8)) for i in range(0,len(data),8))
 return {'ratio':round(im.width/im.height,5),'data':base64.b64encode(packed).decode()}
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 rows=list(csv.DictReader((ROOT/'csv/character_stats.csv').open(encoding='utf-8-sig')));refs=[]
 for file in ['NotoSansJP.ttf']:
  font=ImageFont.truetype(str(ROOT/'scripts/assets/status-name'/file),90)
  for row in rows:
   for shear in [0,-.1,-.2]:refs.append({'id':row['id'],'name':row['name'],**template(row['name'],font,shear)})
 content='// Generated by scripts/build-screen-reader-name-references.py; bounded CSV names, OFL font masks.\nwindow.ScreenReaderNameReferences='+json.dumps(refs,ensure_ascii=False,separators=(',',':'))+';\n'
 out=ROOT/'08_screen_reader/js/screen-reader-name-references.js'
 if args.check:
  if out.read_text()!=content:raise ValueError('Rebuild character-name references')
 else:out.write_text(content)
 print(f'Validated {len(rows)} character names, {len(refs)} local text templates')
if __name__=='__main__':main()
